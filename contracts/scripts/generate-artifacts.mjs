// Writes ts/artifacts.generated.ts from Forge's build output, so TypeScript gets the fixture
// contracts' ABIs as `const` literals (and with them viem's type inference) without needing
// Foundry installed. CI regenerates it and fails if the committed copy differs.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = [
  ["Emitter.sol", "Emitter", "emitter"],
  ["Factory.sol", "Factory", "factory"],
  ["Factory.sol", "Child", "child"],
  ["Token.sol", "Token", "token"],
  ["Router.sol", "Router", "router"],
];

let out = "// Generated by scripts/generate-artifacts.mjs from Forge's output. Do not edit.\n";
for (const [file, name, id] of contracts) {
  const artifact = JSON.parse(readFileSync(join(root, "out", file, `${name}.json`), "utf8"));
  out += `\nexport const ${id}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  out += `\nexport const ${id}Bytecode = "${artifact.bytecode.object}" as const;\n`;
}
writeFileSync(join(root, "ts", "artifacts.generated.ts"), out);
