import { mkdir, readFile, writeFile } from "node:fs/promises";
import { basename, dirname, join, relative } from "node:path";
import { buildGraphQLSchema } from "@tidemark/api";
import { relationsOf, tablesOf } from "@tidemark/schema";
import { printSchema } from "graphql";
import type { ProjectPaths } from "./project.js";

const HEADER = "// Generated by `tidemark codegen`. Do not edit.\n";

/** An import specifier for `to`, from a file in `fromDir`: relative, without the extension. */
function specifier(fromDir: string, to: string): string {
  const path = relative(fromDir, join(dirname(to), basename(to).replace(/\.(m?ts|m?js)$/, "")));
  return path.startsWith(".") ? path : `./${path}`;
}

/** The ambient declaration that types `tidemark:registry` from the project's config. */
export function registryTypes(paths: ProjectPaths): string {
  const config = specifier(paths.root, paths.config);
  return `${HEADER}/// <reference types="@tidemark/engine" />

declare module "tidemark:registry" {
  type Config = (typeof import(${JSON.stringify(config)}))["default"];
  /** The project's handler registry, typed from tidemark.config. */
  export const tidemark: import("@tidemark/engine").Tidemark<Config>;
}
`;
}

/** Writes the file only if its content changed, so watchers do not loop. Returns whether it wrote. */
async function writeIfChanged(path: string, content: string): Promise<boolean> {
  const current = await readFile(path, "utf8").catch(() => undefined);
  if (current === content) return false;
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
  return true;
}

export interface CodegenResult {
  readonly written: readonly string[];
}

/**
 * Writes `tidemark-env.d.ts` (types for `tidemark:registry`) and, given the schema module,
 * `generated/schema.graphql` (the API's SDL, for teams with their own GraphQL tooling).
 */
export async function codegen(paths: ProjectPaths, schema?: Record<string, unknown>): Promise<CodegenResult> {
  const written: string[] = [];
  const env = join(paths.root, "tidemark-env.d.ts");
  if (await writeIfChanged(env, registryTypes(paths))) written.push(env);
  if (schema !== undefined) {
    const sdl = printSchema(buildGraphQLSchema({ tables: tablesOf(schema), relations: relationsOf(schema) }));
    const file = join(paths.root, "generated", "schema.graphql");
    if (await writeIfChanged(file, `# Generated by \`tidemark codegen\`. Do not edit.\n\n${sdl}\n`))
      written.push(file);
  }
  return { written };
}
